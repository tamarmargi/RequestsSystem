using System.Data;
using System.Diagnostics;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace Requests.DAL.Seeding;

/// <summary>
/// Replaces all requests and status history with deterministic test data. Re-runnable: every run
/// deletes the existing rows and inserts the same data again, in a single transaction.
/// </summary>
public class DatabaseSeeder
{
    private const int BatchSize = 10_000;
    private const int CommandTimeoutSeconds = 300;

    private readonly AppDbContext _db;
    private readonly ILogger<DatabaseSeeder> _logger;

    public DatabaseSeeder(AppDbContext db, ILogger<DatabaseSeeder> logger)
    {
        _db = db;
        _logger = logger;
    }

    public async Task SeedAsync(int count, CancellationToken ct)
    {
        _logger.LogInformation("Seeding started: generating {Count} requests", count);

        var stopwatch = Stopwatch.StartNew();
        var data = new RequestGenerator().Generate(count);
        var requestsTable = BuildRequestsTable(data.Requests);
        var historyTable = BuildHistoryTable(data.History);
        _logger.LogInformation(
            "Generated {RequestCount} requests and {HistoryCount} history rows in {ElapsedMs} ms",
            data.Requests.Count, data.History.Count, stopwatch.ElapsedMilliseconds);

        stopwatch.Restart();
        var connection = (SqlConnection)_db.Database.GetDbConnection();
        await _db.Database.OpenConnectionAsync(ct);
        try
        {
            await using var transaction = (SqlTransaction)await connection.BeginTransactionAsync(ct);

            await ExecuteAsync(connection, transaction, "DELETE FROM RequestStatusHistory; DELETE FROM Requests;", ct);

            await BulkInsertAsync(connection, transaction, "Requests", requestsTable, ct);
            await BulkInsertAsync(connection, transaction, "RequestStatusHistory", historyTable, ct);

            // Ids were inserted explicitly as 1..N; move the identity seeds so later inserts continue after them.
            // (RESEED on a table that never had rows makes the next row use the seed itself, hence the guard.)
            await ExecuteAsync(connection, transaction, $"DBCC CHECKIDENT ('Requests', RESEED, {data.Requests.Count});", ct);
            if (data.History.Count > 0)
            {
                await ExecuteAsync(connection, transaction,
                    $"DBCC CHECKIDENT ('RequestStatusHistory', RESEED, {data.History.Count});", ct);
            }

            await transaction.CommitAsync(ct);
        }
        finally
        {
            await _db.Database.CloseConnectionAsync();
        }

        _logger.LogInformation("Inserted seed data in {ElapsedMs} ms", stopwatch.ElapsedMilliseconds);
    }

    private static async Task ExecuteAsync(SqlConnection connection, SqlTransaction transaction, string sql, CancellationToken ct)
    {
        await using var command = new SqlCommand(sql, connection, transaction) { CommandTimeout = CommandTimeoutSeconds };
        await command.ExecuteNonQueryAsync(ct);
    }

    private static async Task BulkInsertAsync(
        SqlConnection connection, SqlTransaction transaction, string tableName, DataTable table, CancellationToken ct)
    {
        using var bulkCopy = new SqlBulkCopy(connection, SqlBulkCopyOptions.KeepIdentity, transaction)
        {
            DestinationTableName = tableName,
            BatchSize = BatchSize,
            BulkCopyTimeout = CommandTimeoutSeconds
        };

        // Explicit mappings by name; RowVersion is generated by SQL Server and is not mapped.
        foreach (DataColumn column in table.Columns)
        {
            bulkCopy.ColumnMappings.Add(column.ColumnName, column.ColumnName);
        }

        await bulkCopy.WriteToServerAsync(table, ct);
    }

    private static DataTable BuildRequestsTable(IReadOnlyList<GeneratedRequest> requests)
    {
        var table = new DataTable("Requests");
        table.Columns.Add("Id", typeof(int));
        table.Columns.Add("Title", typeof(string));
        table.Columns.Add("OrganizationName", typeof(string));
        table.Columns.Add("Status", typeof(byte));
        table.Columns.Add("Priority", typeof(byte));
        table.Columns.Add("AssignedTo", typeof(string));
        table.Columns.Add("CreatedAt", typeof(DateTime));
        table.Columns.Add("UpdatedAt", typeof(DateTime));

        foreach (var r in requests)
        {
            table.Rows.Add(r.Id, r.Title, r.OrganizationName, (byte)r.Status, (byte)r.Priority,
                (object?)r.AssignedTo ?? DBNull.Value, r.CreatedAt, r.UpdatedAt);
        }

        return table;
    }

    private static DataTable BuildHistoryTable(IReadOnlyList<GeneratedStatusChange> history)
    {
        var table = new DataTable("RequestStatusHistory");
        table.Columns.Add("Id", typeof(long));
        table.Columns.Add("RequestId", typeof(int));
        table.Columns.Add("PreviousStatus", typeof(byte));
        table.Columns.Add("NewStatus", typeof(byte));
        table.Columns.Add("ChangedAt", typeof(DateTime));
        table.Columns.Add("ChangedBy", typeof(string));

        foreach (var h in history)
        {
            table.Rows.Add(h.Id, h.RequestId, (byte)h.PreviousStatus, (byte)h.NewStatus, h.ChangedAt, h.ChangedBy);
        }

        return table;
    }
}
